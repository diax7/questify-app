const seenFor = (input: unknown): Seen => {
  const logged: unknown[] = [];
  const headers: Record<string, string> = {};
  const request = { log: { info: (fields: unknown) => logged.push(fields) } };
  const reply = {
    header: (name: string, value: string) => {
      headers[name] = value;
    },
  };
  const answer = answerOf(() =>
    refuse(request as unknown as FastifyRequest, reply as unknown as FastifyReply, input as never),
  );
  return { answer, logged, headers };
};

describe("refuse (tickets), one HTTP answer per refusal", () => {
  it.each(CASES)("answers %j as pinned", (input, expected) => {
    expect(seenFor(input)).toEqual(expected);
  });
});
