const HISTORY_KEYS: ReadonlyMap<string, MessageKey> = new Map(
  HISTORY_GROUPS.flatMap(([key, actions]) => actions.map((action) => [action, key] as const)),
);

/** The words for an audit action in the console's history, or undefined for one without words (its name is shown). */
export function historyKeyOf(action: string): MessageKey | undefined {
  return (
    HISTORY_KEYS.get(action) ??
    (/^console\.[a-z_]+_read$/.test(action) ? "console.history.read" : undefined)
  );
}

/** The takedown reasons the admin picks from (content_hold.reason_code), worded by the reports' own reason texts. */
const TAKEDOWN_REASONS: ReadonlyMap<string, MessageKey> = new Map([
  ["offensive", "reports.reason.offensive"],
  ["hateful", "reports.reason.hateful"],
  ["sexual", "reports.reason.sexual"],
  ["spam", "reports.reason.spam"],
  ["misleading", "reports.reason.misleading"],
  ["other", "reports.reason.other"],
]);

/**
 * The words for a reason kept beside an entry: a takedown keeps one of six fixed codes, shown as the reports' words;
 * every other entry keeps the text an admin typed, which is shown as it is (undefined here).
 */
export function historyReasonKeyOf(action: string, reason: string): MessageKey | undefined {
  return action === "content.unpublish" ? TAKEDOWN_REASONS.get(reason) : undefined;
}
